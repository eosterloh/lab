"""Public datasets the converter knows about, with the license decision.

``usable`` is False when the terms are not clear enough for research
fine-tuning. Those rows are never downloaded and never written.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Source:
    id: str
    repo: str
    role: str
    license: str
    usable: bool
    notes: str
    config: str | None = None
    split: str = "train"
    fmt: str = ""

    def to_dict(self) -> dict[str, str | bool | None]:
        return {
            "id": self.id,
            "repo": self.repo,
            "role": self.role,
            "license": self.license,
            "usable": self.usable,
            "notes": self.notes,
            "config": self.config,
            "split": self.split,
            "fmt": self.fmt,
        }


